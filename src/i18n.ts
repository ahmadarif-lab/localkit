export type Lang = 'id' | 'en';
const DICTS: Record<Lang, Record<string, string>> = { id, en };
const LANG_KEY = 'localkit:lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'id' || saved === 'en') return saved;
  } catch {}
  // English by default; Indonesian is one switch away in Settings or ⌘K
  return 'en';
}

export const lang = signal<Lang>(initialLang());

export function setLang(l: Lang) {
  lang.value = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {}
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang.value];
  const s = (vars?.n === 1 && dict[`${key}.one`]) || dict[key] || key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s;
}

export function formatBytes(n: number) {
  const units = ['B', 'KB', 'MB', 'GB'];
  let i = 0;
  while (n >= 1024 && i < units.length - 1) {
    n /= 1024;
    i++;
  }
  const v = i === 0 ? n : n < 10 ? n.toFixed(1) : Math.round(n);
  return `${String(v).replace('.', lang.value === 'id' ? ',' : '.')} ${units[i]}`;
}
